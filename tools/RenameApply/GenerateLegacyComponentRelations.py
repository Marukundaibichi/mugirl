"""Generate the shared, complete legacy Def/comp relation from the reviewed corpus.

Only Mugirl-era ThingDef/HediffDef relations participate. Each Def is registered
once; feature modules must not replace this full relation with their own subset.
"""
import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path


def generate(corpus: Path) -> str:
    data = corpus.read_bytes()
    relations = defaultdict(set)
    for line in data.decode("utf-8-sig").splitlines():
        if not line or line.startswith("#"):
            continue
        cells = line.split("\t")
        if len(cells) != 9:
            raise ValueError("Expected nine corpus columns: " + line)
        root, name, _, comp, _, _, eras, _, _ = cells
        if root in ("ThingDef", "HediffDef") and "Mugirl" in eras.split(",") and comp != "-":
            relations[(root, name)].add(comp)

    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = ["// <auto-generated />",
             "// 完整旧 Def/组件关系；跨模块共用，不能由某个功能的组件子集替代。",
             "// Corpus SHA-256: " + hashlib.sha256(data).hexdigest(),
             "namespace Mugirl.SaveUpgrade;", "", "internal static class LegacyComponentRelations", "{",
             "    internal static void Register(UpgradeModuleBuilder module)", "    {"]
    for (root, name), comps in sorted(relations.items()):
        args = ", ".join(quote(value) for value in [root, name, *sorted(comps)])
        lines.append("        module.DeclareLegacyComps(" + args + ");")
    return "\n".join([*lines, "    }", "}", ""])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(args.corpus)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8-sig") != result:
            raise SystemExit("Legacy component relations are stale: " + str(args.output))
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(result, encoding="utf-8", newline="\n")
    print("Verified" if args.check else "Generated", "complete legacy component relations")


if __name__ == "__main__":
    main()
