"""Generate conservative MooGirl-only exact Def markers inside SaveUpgrade.

python tools/RenameApply/GenerateEraMarkers.py --write [--report <json>]
Without --write, compare the generated source byte-for-byte with the saved source.
Only audited era-branded names are added; no broad substring glob or unbranded name
from the historical marker inventory becomes a discard marker.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path


DERIVED_RACE_NAMES = {
    "Corpse_MooGirl": "Published cb25751:1.6/Defs/ThingDefs_Races/MooGirl_Race.xml: race MooGirl inherits BasePawn and does not override corpse defaults; 1.6 MVID 61e4173561894da49d210260257b5097, ImpliedCorpseDefs 06009284 and RaceProperties hasCorpse=true. Inferred from published race and engine, not observed in a save.",
    "Meat_MooGirl": "Same published race has no meat/flesh override; 1.6 MVID 61e4173561894da49d210260257b5097, ImpliedMeatDefs 06009294, hasMeat/hasCorpse=true, FleshType defaults to Normal. Inferred from published race and engine, not observed in a save.",
}
PREFIXES = ("MooGirl", "MuGirl")


def tsv(path: Path):
    return [line.split("\t") for line in path.read_text(encoding="utf-8-sig").splitlines() if line and not line.startswith("#")]


def select_names(root: Path):
    inventory_path = root / "tools/RenameApply/specs/moogirl-era-markers.json"
    corpus_path = root / "Source/Tests/MugirlRace.Validation/Baselines/legacy/legacy-defs.tsv"
    inventory = json.loads(inventory_path.read_text(encoding="utf-8-sig"))
    rows = tsv(corpus_path)
    # Any use in a supported era, even informational/dev evidence, vetoes automatic discard.
    supported = {row[1] for row in rows if "Mugirl" in row[4].split(",")}
    marked = {item["name"] for item in inventory["defs"]}
    published_early = {row[1] for row in rows if "MooGirl" in row[4].split(",") and "published" in row[3].split(",")}
    exact = set()
    accepted = []
    excluded = []
    for row in rows:
        database, name, kind, tiers, eras, first, last = row[:7]
        if "MooGirl" not in eras.split(",") or name.startswith(PREFIXES):
            continue
        reason = None
        if name in supported:
            reason = "also present in supported Mugirl-era corpus; preserve"
        elif not any(prefix in name for prefix in PREFIXES):
            reason = "unbranded name cannot identify the unsupported era; preserve"
        elif "published" not in tiers.split(","):
            reason = "no published MooGirl-era evidence; preserve"
        elif kind.startswith("implied:"):
            prefix = kind.removeprefix("implied:") + "_"
            source = name.removeprefix(prefix)
            if not name.startswith(prefix) or source not in marked or source not in published_early:
                reason = "derived name has no published source Def in marker inventory; preserve"
        elif name not in marked:
            reason = "name absent from reviewed historical marker inventory; preserve"
        evidence = {"root": database, "name": name, "kind": kind, "tiers": tiers, "eras": eras, "first": first, "last": last}
        if reason:
            excluded.append({**evidence, "reason": reason})
        else:
            exact.add(name)
            accepted.append(evidence)
    for name in DERIVED_RACE_NAMES:
        if name in supported:
            raise ValueError(f"published-race derivation conflicts with supported-era name: {name}")
        if "MooGirl" not in marked or "MooGirl" not in published_early:
            raise ValueError("historical MooGirl race evidence disappeared")
        exact.add(name)
    if any("*" in name or "?" in name or name.startswith(PREFIXES) for name in exact):
        raise ValueError("exact entries must be literal non-prefix names")
    inputs = {str(path.relative_to(root)).replace("\\", "/"): hashlib.sha256(path.read_bytes()).hexdigest() for path in (inventory_path, corpus_path)}
    return sorted(exact), {"inputs": inputs, "prefixPatterns": [prefix + "*" for prefix in PREFIXES], "exactNames": sorted(exact), "acceptedCorpusRows": accepted, "derivedFromPublishedRace": DERIVED_RACE_NAMES, "excluded": excluded}


def render(exact, report):
    hashes = "\n".join("// " + name + ": " + sha for name, sha in report["inputs"].items())
    values = [prefix + "*" for prefix in PREFIXES] + exact
    rows = "\n".join("        " + json.dumps(name) + "," for name in values)
    return f'''// <auto-generated />
// 由 tools/RenameApply/GenerateEraMarkers.py 生成；默认校验，--write 才更新。
{hashes}
namespace Mugirl.SaveUpgrade;

/// <summary>
/// 不受支持时代的名称边界：两个既定前缀和经发布语料核实的精确名称。
/// 不把通用名字或受支持 Mugirl 时代仍使用的名字作为时代标记；派生名称也逐个登记。
/// </summary>
internal static class MooGirlEraNames
{{
    /// <summary>每个表格构建器持有独立列表，模块登记不会修改共享的静态集合。</summary>
    internal static List<string> CreatePatterns() =>
    [
{rows}
    ];
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    exact, report = select_names(root)
    output = root / "Source/MugirlRace/SaveUpgrade/Engine/Tables/MooGirlEraNames.Generated.cs"
    expected = render(exact, report)
    if args.write:
        output.write_text(expected, encoding="utf-8", newline="\n")
    elif not output.is_file() or output.read_bytes() != expected.encode("utf-8"):
        raise SystemExit("Era marker source differs from the audited inputs; regenerate with --write and review.")
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(exact)} exact names + {len(PREFIXES)} established prefix patterns; {len(report['excluded'])} corpus rows conservatively excluded.")


if __name__ == "__main__":
    main()
