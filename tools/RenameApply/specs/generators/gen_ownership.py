"""spec/final/ownership-postR2.json: the one Wave S owner of every Source/ and 1.7/ file of the post-R2 tree (decisions.md
section 3). Rules: ownership.py. Usage: gen_ownership.py <post-R2 tree> <R2 applied json>. Exit 1 when a file has no owner or
several owners (fix HAND in ownership.py or the module specs)."""
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from common import FINAL, load_json, save_json
from ownership import HAND, MODULES, Ownership, load_specs

tree = Path(sys.argv[1])
applied = load_json(Path(sys.argv[2]))
r, r2 = load_specs()
own = Ownership(tree, r, r2, applied)
files, problems = own.resolve()
doc = {
    "_doc": "Wave S owner of every file under Source/ and 1.7/ after R2 (decisions.md section 3; C09-C11, C22, C24). Generated by "
            "spec/final/_gen/gen_ownership.py from the module specs, the R2 split owners and the HAND table in ownership.py; the spec "
            "linter (L16) recomputes it and requires exactly one owner per file. 'stalePlanned' lists planned Wave S file names of the "
            "module specs that no post-R2 file maps to (the owner creates them in Wave S).",
    "tree": str(tree),
    "modules": MODULES,
    "hand": [{"path": p, "module": m, "reason": why} for p, m, why in HAND],
    "counts": dict(sorted(Counter(v["module"] for v in files.values()).items())),
    "files": {k: v["module"] for k, v in sorted(files.items())},
    "by": {k: v["by"] for k, v in sorted(files.items())},
    "stalePlanned": own.stale,
    "problems": problems,
}
save_json(FINAL / "ownership-postR2.json", doc)
print(f"ownership: {len(files)} files owned, {len(problems)} problem(s), {len(own.stale)} stale planned names; {doc['counts']}")
for p in problems[:80]:
    print("  PROBLEM", p["file"], "-", p["problem"])
sys.exit(1 if problems else 0)
