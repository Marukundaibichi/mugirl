using System.Diagnostics;
using System.Text;
using System.Text.Json;
using System.Xml.Linq;
using RenameApply.CSharp;
using RenameApply.Xml;

namespace RenameApply;

/// <summary>
/// 把语义验证使用的编译输入顺序保存为构建输入。只重排项目已经选择的 Compile 项，
/// 保留链接、条件与 metadata；不在清单中的新源码继续按项目原有顺序编译。
/// </summary>
public sealed class CompileOrderPass(RepoPaths repo, RunReport report, CSharpPass cs)
{
    public const string PropsName = "CompileOrder.props";
    private const string Label = "MugirlCompileOrder";
    private const string TargetName = "MugirlPreserveCompileOrder";
    private const string Marker = "RenameApply compile order v1";

    public void Run(List<PendingWrite> writes)
    {
        if (cs.VerificationFailed) { return; }
        string projectPath = cs.Main.ProjectPath;
        string directory = Path.GetDirectoryName(projectPath)!;
        string propsPath = Path.Combine(directory, PropsName);
        string typeOrderPath = Path.Combine(directory, "TypeOrder.txt");
        if (!File.Exists(repo.Full("Source/Build/MugirlRace.MetadataOrder/MetadataOrder.targets")))
        {
            report.Error("metadata-order-tool", "Source/Build/MugirlRace.MetadataOrder is required before applying the refactor.");
            return;
        }
        IReadOnlyList<string> orderedPaths = cs.FinalCompileOrder();
        if (orderedPaths.Distinct(StringComparer.OrdinalIgnoreCase).Count() != orderedPaths.Count)
        {
            report.Error("compile-order-duplicate", "The final compilation contains duplicate source paths.");
            return;
        }
        string[] relativePaths = orderedPaths.Select(p => Path.GetRelativePath(directory, p).Replace('\\', '/')).ToArray();
        TextFileData projectData = TextFileData.Read(projectPath);
        string projectText = PendingText(writes, projectPath) ?? projectData.Text;
        string? previousProps = PendingText(writes, propsPath) ?? (File.Exists(propsPath) ? TextFileData.Read(propsPath).Text : null);
        if (previousProps != null && !previousProps.Contains(Marker, StringComparison.Ordinal))
        {
            report.Error("compile-order-owned-file", $"{repo.Rel(propsPath)} already exists and was not generated by RenameApply.");
            return;
        }

        var project = XDocument.Parse(projectText, LoadOptions.PreserveWhitespace);
        XElement root = project.Root ?? throw new ToolException("The main project has no root element.");
        List<XElement> imports = root.Elements().Where(e => e.Name.LocalName == "Import"
            && ((string?)e.Attribute("Label") == Label || (string?)e.Attribute("Project") == PropsName)).ToList();
        if (imports.Count > 1 || imports.Any(e => (string?)e.Attribute("Project") != PropsName || e.Attribute("Condition") != null))
        {
            report.Error("compile-order-import", "CompileOrder.props must have one unconditional project import.", repo.Rel(projectPath));
            return;
        }
        string nl = projectData.NewLine;
        if (imports.Count == 0)
        {
            string closing = "</" + root.Name.LocalName + ">";
            int at = projectText.LastIndexOf(closing, StringComparison.Ordinal);
            if (at < 0)
            {
                report.Error("compile-order-import", "Cannot locate the project's closing element.", repo.Rel(projectPath));
                return;
            }
            projectText = projectText.Insert(at, $"  <Import Project=\"{PropsName}\" Label=\"{Label}\" />{nl}");
        }

        string props = CreateProps(relativePaths, nl);
        string typeOrder = cs.BuildTypeOrderManifest(File.Exists(typeOrderPath) ? File.ReadAllText(typeOrderPath) : null);
        const string metadataImport = "../Build/MugirlRace.MetadataOrder/MetadataOrder.targets";
        XElement finalProject = XDocument.Parse(projectText).Root!;
        List<XElement> metadataImports = finalProject.Elements().Where(e => e.Name.LocalName == "Import"
            && ((string?)e.Attribute("Label") == "MugirlMetadataOrder" || (string?)e.Attribute("Project") == metadataImport)).ToList();
        if (metadataImports.Count > 1 || metadataImports.Any(e => (string?)e.Attribute("Project") != metadataImport || e.Attribute("Condition") != null))
        {
            report.Error("metadata-order-import", "MetadataOrder.targets must have one unconditional project import.", repo.Rel(projectPath));
            return;
        }
        if (metadataImports.Count == 0)
        {
            int at = projectText.LastIndexOf("</" + root.Name.LocalName + ">", StringComparison.Ordinal);
            projectText = projectText.Insert(at, $"  <Import Project=\"{metadataImport}\" Label=\"MugirlMetadataOrder\" />{nl}");
        }
        // 用真正的 MSBuild 执行待写入目标，验证顺序、新文件兜底、条件排除与 metadata。
        // 该探针不需要源码文件存在，不构建或部署模组；dry-run 同样运行。
        VerifyWithMsBuild(props, relativePaths);
        Upsert(writes, projectPath, projectText, projectData.Bom);
        Upsert(writes, propsPath, props, File.Exists(propsPath) && TextFileData.Read(propsPath).Bom);
        Upsert(writes, typeOrderPath, typeOrder.ReplaceLineEndings(nl), false);
        report.Info("compile-order-verified", $"{relativePaths.Length} existing source files retain compiler order; unlisted Compile items remain automatic.", repo.Rel(propsPath));
        report.FileOps.Add(new FileOp
        {
            Op = File.Exists(propsPath) ? "update" : "create", To = repo.Rel(propsPath),
            Note = "compiler order, with automatic inclusion of unlisted source files",
        });
        report.FileOps.Add(new FileOp
        {
            Op = File.Exists(typeOrderPath) ? "update" : "create", To = repo.Rel(typeOrderPath),
            Note = "mapped metadata order, verified against emitted DLL and portable PDB",
        });
    }

    private static string? PendingText(IEnumerable<PendingWrite> writes, string path)
        => writes.LastOrDefault(w => string.Equals(w.OutFull, path, StringComparison.OrdinalIgnoreCase) && w.Text != null)?.Text;

    private static void Upsert(List<PendingWrite> writes, string path, string text, bool bom)
    {
        int index = writes.FindIndex(w => string.Equals(w.OutFull, path, StringComparison.OrdinalIgnoreCase));
        if (index >= 0)
        {
            writes[index] = writes[index] with { Text = text, Bom = bom };
        }
        else if (!File.Exists(path) || TextFileData.Read(path).Text != text)
        {
            writes.Add(new PendingWrite(path, text, bom, null));
        }
    }

    private static string EscapeMsBuild(string value)
    {
        var text = new StringBuilder();
        foreach (char c in value)
        {
            if (c is '%' or '$' or '@' or '(' or ')' or ';' or '?' or '*' or '\'' or ',' or ' ')
            {
                text.Append('%').Append(((int)c).ToString("X2", System.Globalization.CultureInfo.InvariantCulture));
            }
            else
            {
                text.Append(c);
            }
        }
        return text.ToString();
    }

    internal static string CreateProps(IReadOnlyList<string> paths, string newLine)
    {
        var items = new XElement("ItemGroup",
            new XElement("_MugirlOrderedCompile", new XAttribute("Remove", "@(_MugirlOrderedCompile)")),
            new XElement("_MugirlRemainingCompile", new XAttribute("Remove", "@(_MugirlRemainingCompile)")));
        foreach (string path in paths)
        {
            string full = $"$([MSBuild]::NormalizePath($(MSBuildProjectDirectory), {EscapeMsBuild(path)}))";
            items.Add(new XElement("_MugirlOrderedCompile", new XAttribute("Include", "@(Compile)"),
                new XAttribute("Condition", $"'%(Compile.FullPath)' == '{full}'")));
        }
        items.Add(new XElement("_MugirlRemainingCompile", new XAttribute("Include", "@(Compile)"), new XAttribute("Exclude", "@(_MugirlOrderedCompile)")));
        items.Add(new XElement("Compile", new XAttribute("Remove", "@(Compile)")));
        items.Add(new XElement("Compile", new XAttribute("Include", "@(_MugirlOrderedCompile);@(_MugirlRemainingCompile)")));
        return new XDocument(new XElement("Project",
            new XComment(" " + Marker + ": 保持已有源码顺序；新增源码由项目默认 Compile 项自动追加，不必登记。 "),
            new XElement("Target", new XAttribute("Name", TargetName), new XAttribute("BeforeTargets", "CoreCompile"), items)))
            .ToString().ReplaceLineEndings(newLine) + newLine;
    }

    private static void VerifyWithMsBuild(string props, IReadOnlyList<string> paths)
    {
        string temporary = Path.Combine(Path.GetTempPath(), "RenameApply-compile-order-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(temporary);
        string propsPath = Path.Combine(temporary, PropsName);
        string projectPath = Path.Combine(temporary, "OrderProbe.proj");
        try
        {
            File.WriteAllText(propsPath, props);
            // 留出一个清单项不放入 Compile，证明重排不会把条件排除的文件加回来。
            string[] selected = paths.Skip(1).Reverse().ToArray();
            string[] extras = ["__RenameApply_Unlisted_First.cs", "__RenameApply_Unlisted_Last.cs"];
            string[] input = extras.Take(1).Concat(selected).Concat(extras.Skip(1)).ToArray();
            var group = new XElement("ItemGroup", input.Select((path, i) =>
                new XElement("Compile", new XAttribute("Include", EscapeMsBuild(path)), new XElement("RenameApplyProof", i))));
            var project = new XDocument(new XElement("Project", group,
                new XElement("Import", new XAttribute("Project", PropsName))));
            File.WriteAllText(projectPath, project.ToString());
            var start = new ProcessStartInfo("dotnet")
            {
                WorkingDirectory = Environment.CurrentDirectory, RedirectStandardOutput = true, RedirectStandardError = true,
                UseShellExecute = false, CreateNoWindow = true, StandardOutputEncoding = Encoding.UTF8,
            };
            foreach (string argument in new[] { "msbuild", projectPath, "-nologo", "-v:q", "-nodeReuse:false", "-t:" + TargetName, "-getItem:Compile" })
            {
                start.ArgumentList.Add(argument);
            }
            start.Environment["DOTNET_CLI_UI_LANGUAGE"] = "en";
            using Process process = Process.Start(start) ?? throw new ToolException("Cannot start the compile-order MSBuild probe.");
            Task<string> error = process.StandardError.ReadToEndAsync();
            string output = process.StandardOutput.ReadToEnd();
            process.WaitForExit();
            int jsonAt = output.IndexOf('{');
            if (process.ExitCode != 0 || jsonAt < 0)
            {
                throw new ToolException($"Compile-order MSBuild probe failed (exit {process.ExitCode}): {output}\n{error.Result}");
            }
            using JsonDocument json = JsonDocument.Parse(output[jsonAt..]);
            JsonElement[] actual = json.RootElement.GetProperty("Items").GetProperty("Compile").EnumerateArray().ToArray();
            string[] expected = paths.Skip(1).Concat(extras).Select(p => Path.GetFullPath(Path.Combine(temporary, p))).ToArray();
            string[] found = actual.Select(e => e.GetProperty("FullPath").GetString()!).ToArray();
            if (!expected.SequenceEqual(found, StringComparer.OrdinalIgnoreCase))
            {
                throw new ToolException("Compile-order MSBuild probe changed the selected file set or did not preserve the requested order.");
            }
            var proofs = input.Select((path, i) => (Path: Path.GetFullPath(Path.Combine(temporary, path)), Proof: i.ToString(System.Globalization.CultureInfo.InvariantCulture)))
                .ToDictionary(e => e.Path, e => e.Proof, StringComparer.OrdinalIgnoreCase);
            foreach (JsonElement item in actual)
            {
                if (item.GetProperty("RenameApplyProof").GetString() != proofs[item.GetProperty("FullPath").GetString()!])
                {
                    throw new ToolException("Compile-order MSBuild probe lost source item metadata.");
                }
            }
        }
        finally
        {
            // 只删除本次创建的两个已知文件，再删除空目录；不递归处理任何目录。
            File.Delete(projectPath);
            File.Delete(propsPath);
            Directory.Delete(temporary);
        }
    }
}
