namespace MugirlRace.Validation.Legacy;

/// <summary>
/// 一个语料文件：每行是一条事实（固定的事实列）加上聚合列 <c>tiers</c>、<c>eras</c>、<c>first</c>、<c>last</c>（来源层级、时代、
/// 按 builds.tsv 顺序的第一个与最后一个构建）。行按序数排序，LF，UTF-8 无 BOM。
/// </summary>
/// <remarks>
/// 聚合列可以合并：同一事实在旧文件中的行与本次提取的结果取层级与时代的并集、first 取较早、last 取较晚的构建，所以只追加的合并
/// 不会因为某个输入不再存在（存档被覆盖、创意工坊更新）而降低一行的层级。
/// </remarks>
internal sealed class CorpusTable
{
    /// <summary>事实列之后的聚合列。</summary>
    public static readonly string[] AggregateColumns = ["tiers", "eras", "first", "last"];

    private readonly Dictionary<string, Aggregate> rows = new(StringComparer.Ordinal);

    public CorpusTable(string fileName, string description, params string[] columns)
    {
        FileName = fileName;
        Description = description;
        Columns = columns;
    }

    public string FileName { get; }

    public string Description { get; }

    /// <summary>事实列（也是行键）。</summary>
    public IReadOnlyList<string> Columns { get; }

    public int Count => rows.Count;

    /// <summary>记录 <paramref name="build"/> 含有这条事实。</summary>
    public void Add(IReadOnlyList<string> facts, BuildInfo build)
    {
        if (facts.Count != Columns.Count)
        {
            throw new ArgumentException($"{FileName}: expected {Columns.Count} columns, got {facts.Count}.", nameof(facts));
        }

        string key = string.Join('\t', facts.Select(Sanitize));
        if (!rows.TryGetValue(key, out Aggregate? aggregate))
        {
            rows[key] = aggregate = new Aggregate();
        }

        aggregate.Add(build.Tier, build.Era, build.Id);
    }

    /// <summary>
    /// 合并旧文件中的一行（只追加）：本次没有产生的事实原样加入，已有的事实合并聚合列。返回该事实是否只来自旧文件。
    /// </summary>
    public bool Merge(string line)
    {
        string key = KeyOf(line, Columns.Count);
        string[] aggregate = line.Length > key.Length ? line[(key.Length + 1)..].Split('\t') : [];
        if (aggregate.Length != AggregateColumns.Length)
        {
            throw new FormatException($"{FileName}: malformed line '{line}'.");
        }

        bool retained = !rows.ContainsKey(key);
        if (retained)
        {
            rows[key] = new Aggregate();
        }

        Aggregate target = rows[key];
        foreach (string tier in aggregate[0].Split(','))
        {
            target.Add(tier, aggregate[1], aggregate[2]);
        }

        target.Add(null, null, aggregate[3]);
        return retained;
    }

    /// <summary>文件头（以 <c>#</c> 开头的注释行，含列名）。</summary>
    public IEnumerable<string> Header()
    {
        yield return "# " + FileName + ": " + Description;
        yield return "# Generated by MugirlRace.Validation --extract-legacy-schema (tools/Export-LegacySchema.ps1); append-only, never edit by hand.";
        yield return "# columns: " + string.Join('\t', Columns.Concat(AggregateColumns));
    }

    /// <summary>数据行（序数排序）。<paramref name="order"/> 给出构建在 builds.tsv 中的位置（first/last 按它取）。</summary>
    public IEnumerable<string> Render(IReadOnlyDictionary<string, int> order)
        => rows.OrderBy(pair => pair.Key, StringComparer.Ordinal).Select(pair => pair.Key + "\t" + pair.Value.Render(order));

    /// <summary>行键：一行的前 <paramref name="columns"/> 列。</summary>
    public static string KeyOf(string line, int columns)
    {
        int index = -1;
        for (int i = 0; i < columns; i++)
        {
            index = line.IndexOf('\t', index + 1);
            if (index < 0)
            {
                return line;
            }
        }

        return line[..index];
    }

    // 字段中不允许制表符与换行（会破坏 TSV）。
    private static string Sanitize(string value) => value.Length == 0 ? "-" : value.Replace('\t', ' ').Replace('\r', ' ').Replace('\n', ' ');

    private sealed class Aggregate
    {
        private readonly SortedSet<string> tiers = new(StringComparer.Ordinal);
        private readonly SortedSet<string> eras = new(StringComparer.Ordinal);
        private readonly HashSet<string> builds = new(StringComparer.Ordinal);

        public void Add(string? tier, string? era, string build)
        {
            if (tier is { Length: > 0 } and not "-")
            {
                tiers.Add(tier);
            }

            foreach (string part in (era ?? "").Split(','))
            {
                if (part is { Length: > 0 } and not "-")
                {
                    eras.Add(part);
                }
            }

            builds.Add(build);
        }

        public string Render(IReadOnlyDictionary<string, int> order)
        {
            List<string> ordered = builds.OrderBy(id => order.TryGetValue(id, out int position) ? position : int.MaxValue).ThenBy(id => id, StringComparer.Ordinal).ToList();
            return string.Join('\t', string.Join(",", tiers), eras.Count == 0 ? "-" : string.Join(",", eras), ordered[0], ordered[^1]);
        }
    }
}
